// Fetches real coordinates from OpenStreetMap Nominatim for every place in
// seeds/001_seed_initial.sql (which only lists SURVEY.md localities) and writes
// seeds/002_seed_known_place_coordinates.sql with latitude, longitude, source_query, queried_on.
//
// Usage:  node backend/database/fetch-nominatim.js
// Respects the Nominatim usage policy: custom User-Agent, max 1 request/second, no retries storm.
// Places that return nothing are skipped and listed (they stay NULL / TODO).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const SEED_IN = path.join(dir, 'seeds/001_seed_initial.sql');
const SEED_OUT = path.join(dir, 'seeds/002_seed_known_place_coordinates.sql');
const QUERIED_ON = '2026-11-19'; // date recorded with every row, as requested
const USER_AGENT = 'StudRide-ULBS-coursework/0.1 (student project; contact via GitHub repo ProiectWeb1)';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const sql = (s) => s.replace(/'/g, "''");

const places = [...fs.readFileSync(SEED_IN, 'utf8').matchAll(/^\s*\('([^']+)',\s*'([^']+)'\)/gm)]
  .map((m) => ({ city: m[1], name: m[2] }));

// Disambiguation for names where the plain query returned the wrong place (checked against the
// survey route). Boița is on the Valea Oltului route (Sibiu county), not the Hunedoara hamlet.
const QUERY_OVERRIDES = { 'Boița': 'Boița, Sibiu, Romania' };

const rows = [];
const missing = [];
for (const p of places) {
  const query = QUERY_OVERRIDES[p.name] ?? `${p.name}, Romania`;
  const url = 'https://nominatim.openstreetmap.org/search?' +
    new URLSearchParams({ q: query, format: 'jsonv2', limit: '1', countrycodes: 'ro' });
  try {
    const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT, 'Accept-Language': 'ro' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const [hit] = await res.json();
    if (!hit) throw new Error('no result');
    rows.push({ ...p, query, lat: Number(hit.lat).toFixed(7), lon: Number(hit.lon).toFixed(7), display: hit.display_name });
    console.log(`ok   ${query} -> ${hit.lat}, ${hit.lon}  (${hit.display_name})`);
  } catch (e) {
    missing.push(p.name);
    console.log(`FAIL ${query}: ${e.message}`);
  }
  await sleep(1100); // 1 req/sec limit
}

const out = [
  '-- GENERATED by backend/database/fetch-nominatim.js from real Nominatim queries.',
  `-- queried_on ${QUERIED_ON}. display_name in the comments is for human review (ambiguous names!).`,
  '-- Re-running the seed re-applies these values; idempotent.',
  ...rows.map((r) =>
    `-- ${r.display}\nUPDATE known_places SET latitude = ${r.lat}, longitude = ${r.lon}, ` +
    `source = 'OpenStreetMap/Nominatim', source_query = '${sql(r.query)}', queried_on = '${QUERIED_ON}' ` +
    `WHERE city = '${sql(r.city)}' AND name = '${sql(r.name)}';`),
  missing.length ? `-- NOT FOUND (left NULL, fill manually): ${missing.join(', ')}` : '-- all places found',
  '',
].join('\n');
fs.writeFileSync(SEED_OUT, out);
console.log(`\nWrote ${rows.length}/${places.length} rows to ${SEED_OUT}`);
if (missing.length) console.log(`Missing: ${missing.join(', ')}`);
